def main() -> int:
    eval_root = Path(__file__).resolve().parent.parent
    tables_dir = eval_root / "docs" / "publication" / "tables"
    figures_dir = eval_root / "docs" / "publication" / "figures"
    appendix_file = eval_root / "docs" / "publication" / "APPENDIX_A_RESULTS.md"

    print("Gathering benchmark telemetry across all research packages...")

    # 1. IAA
    corpus_path = eval_root / "research" / "annotations" / "dual_annotator_corpus.json"
    with open(corpus_path, encoding="utf-8") as f:
        tasks = json.load(f)
    iaa_calc = IAACalculator(tasks)
    iaa_data = iaa_calc.generate_full_results()

    # 2. Arch Engines
    arch_data = run_arch_benchmark()

    # 3. Cross-Code
    cross_data = run_cross_code_benchmark()

    # 4. Judge Sensitivity
    judge_data = generate_benchmark_report()

    print(f"Generating LaTeX booktabs tables in: {tables_dir}...")
    generate_latex_tables(iaa_data, arch_data, cross_data, judge_data, tables_dir)

    print(f"Generating 300 DPI publication figures in: {figures_dir}...")
    generate_publication_figures(arch_data, judge_data, iaa_data, figures_dir)

    print(f"Writing thesis summary appendix in: {appendix_file}...")
    generate_appendix_markdown(appendix_file)

    print("\nAll academic publication artifacts successfully generated!")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
