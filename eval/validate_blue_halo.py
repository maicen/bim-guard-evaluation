# Plain dataclasses standing in for IfcElement — Phase 3 validates algorithm
# logic, not IFC I/O, so each element carries its bounding box directly
# rather than a real ifcopenshell placement/representation to extract it
# from. All coordinates are hand-computed and fixed, so every run of this
# script produces byte-identical bounding boxes.


@dataclass
class MockElement:
    id: str
    ifc_class: str
    material: str
    description: str
    bbox_mm: BoundingBox

    def geometry(self) -> ElementGeometry:
        return ElementGeometry(element_id=self.id, ifc_class=self.ifc_class, bbox_mm=self.bbox_mm)


def bbox(min_xyz: tuple, max_xyz: tuple) -> BoundingBox:
    return BoundingBox(min=Point3D(*min_xyz), max=Point3D(*max_xyz))


