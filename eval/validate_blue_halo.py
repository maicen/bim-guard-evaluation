def scenario_4(config: ClearanceConfig) -> dict:
    _out("\n" + "-" * 70)
    _out("SCENARIO 4 — rectangular duct, threshold check")
    _out("-" * 70)
    _print_element(DUCT_4)

    sx, sy, _sz = DUCT_4.bbox_mm.size
    cross_section_m2 = (sx / 1000.0) * (sy / 1000.0)
    threshold_m2 = config.duct_area_threshold_m2
    if threshold_m2 is None:
        triggers_bracing = None
        _out(f"\n  Cross-section: {cross_section_m2:.2f} sqm  vs  threshold: not specified in this "
             f"config (data gap — see config.data_gaps)")
    else:
        triggers_bracing = cross_section_m2 > threshold_m2
        _out(f"\n  Cross-section: {cross_section_m2:.2f} sqm  vs  threshold: {threshold_m2:.2f} sqm")
    _out(f"  RESULT: duct area exceeds bracing threshold -> {triggers_bracing}")

    results = {}
    for variant, rule in sorted(config.rules.items()):
        if rule.brace_type is not BraceType.ANGLE_IRON:
            continue
        halo = generate_halo_volume_from_geometry(DUCT_4.geometry(), rule.brace_type, rule)
        clashes = detect_halo_clash_against_geometry(halo, [DUCT_4.geometry()])
        _print_halo(variant, halo, rule)
        _print_clashes(clashes)
        results[variant] = (halo, clashes)
    return results


def scenario_5(config: ClearanceConfig) -> dict:
    _out("\n" + "-" * 70)
    _out("SCENARIO 5 — multi-system plant room bay, brace-type comparison")
    _out("-" * 70)
    for el in (PIPE_5, DUCT_5, CONDUIT_5, BEAM_5):
        _print_element(el)

    candidates = [PIPE_5.geometry(), DUCT_5.geometry(), CONDUIT_5.geometry(), BEAM_5.geometry()]

    _out("\n  Evaluating PIPE-005 against every brace type in the config:")
    results = {}
    for variant, rule in sorted(config.rules.items()):
        halo = generate_halo_volume_from_geometry(PIPE_5.geometry(), rule.brace_type, rule)
        clashes = detect_halo_clash_against_geometry(halo, candidates)
        _print_halo(variant, halo, rule)
        _print_clashes(clashes)
        results[variant] = (halo, clashes)

    _out("\n  Comparison table (brace_type | clearance_mm | halo_volume_mm3 | clash_count):")
    _out(f"  {'variant':12s} {'clearance_mm':>12s} {'halo_volume_mm3':>18s} {'clashes':>8s}")
    for variant, (halo, clashes) in sorted(results.items()):
        _out(f"  {variant:12s} {halo.clearance_mm:12.1f} {halo.halo_bbox_mm.volume_mm3:18,.0f} {len(clashes):8d}")

    best_variant, best_halo, best_clashes = _recommend_brace_type(results)
    _out(f"\n  RESULT: recommended brace type = {best_variant} "
         f"({len(best_clashes)} clash(es), {best_halo.halo_bbox_mm.volume_mm3:,.0f} mm^3 halo volume)")

    pset = export_halo_to_ifc_property_set(best_halo)
    _out(f"\n  Pset preview (export_halo_to_ifc_property_set, recommended brace type):")
    for key, value in pset["BlueHalo_ClearanceVolume"].items():
        _out(f"    {key:20s} = {value}")

    return results


# ═══════════════════════════════════════════════════════════════════════════
# PHASE 4 — BCF / Pset export integration
# ═══════════════════════════════════════════════════════════════════════════


def phase4_bcf_pset_export(
    s1_results: dict,
    s2_result: tuple,
    s5_results: dict,
) -> tuple:
    """Feed the real HaloVolume / ClashReport objects from scenarios 1, 2,
    and 5 through Module 5's Blue Halo exporter — Phase 2 config loading +
    Phase 1 generation/detection + Phase 4 BCF/Pset export, end to end.

    Returns:
        (bcf_zip_bytes, bcf_zip_names, pset_dict) for the validation checks.
    """
    _out("\n" + "=" * 70)
    _out("  PHASE 4 — BCF / Pset export integration")
    _out("=" * 70)

    s2_halo, s2_clashes = s2_result

    halos_by_id: dict[str, HaloVolume] = {}
    for halo, _clashes in s1_results.values():
        halos_by_id[halo.id] = halo
    halos_by_id[s2_halo.id] = s2_halo
    for halo, _clashes in s5_results.values():
        halos_by_id[halo.id] = halo

    all_clashes: list[ClashReport] = list(s2_clashes)
    for _halo, clashes in s5_results.values():
        all_clashes.extend(clashes)

    _out(f"\n  Exporting {len(all_clashes)} clash(es) across {len(halos_by_id)} halo volume(s) "
         f"(scenarios 1, 2, 5) to a BCF 2.1 ZIP...")
    zip_bytes = generate_bcf_zip_from_halo_clashes(
        all_clashes, project_id="BLUE-HALO-VALIDATION-001", halos=halos_by_id
    )
    _out(f"  BCF ZIP size: {len(zip_bytes):,} bytes")

    with zipfile.ZipFile(BytesIO(zip_bytes)) as zf:
        names = zf.namelist()

    _out(f"  ZIP entries ({len(names)}):")
    for name in sorted(names):
        _out(f"    {name}")

    # One representative halo for the Pset export — the Scenario 2 CHW pipe.
    pset = generate_pset_halo_reservation(s2_halo)
    _out(f"\n  {PSET_HALO_RESERVATION} (Scenario 2 CHW pipe halo):")
    for key, value in pset[PSET_HALO_RESERVATION].items():
        _out(f"    {key:22s} = {value}")

    return zip_bytes, names, pset, len(all_clashes)


# ═══════════════════════════════════════════════════════════════════════════
# Validation checks
# ═══════════════════════════════════════════════════════════════════════════


def run_validation_checks(
    config: ClearanceConfig,
    config_path: str,
    scenario1_results: dict,
    scenario2_clashes: list,
    *,
    bcf_zip_names: list,
    expected_clash_count: int,
    pset: dict,
) -> bool:
    _out("\n" + "=" * 70)
    _out("  VALIDATION CHECKS")
    _out("=" * 70)

    checks: list[tuple[str, bool]] = []

    # 1. Config loads correctly: compare the loaded ClearanceConfig against
    #    the source JSON file itself (not a hardcoded expectation), so this
    #    check holds for whichever config is loaded — real or mock.
    with open(config_path, encoding="utf-8") as f:
        raw_config = json.load(f)
    config_ok = (
        config.jurisdiction == raw_config["metadata"]["jurisdiction"]
        and set(config.rules.keys()) == set(raw_config["brace_types"].keys())
        and config.duct_area_threshold_m2 == raw_config["thresholds"]["duct_area_sqm"]
        and config.pipe_diameter_threshold_mm == raw_config["thresholds"]["pipe_diameter_mm"]
    )
    checks.append((f"Config loads correctly (jurisdiction, brace_types, thresholds match {config_path})", config_ok))

    # 2. Bounding box math: expansion and intersection.
    probe = bbox((0, 0, 0), (100, 100, 100))
    expanded = probe.expanded(10)
    expansion_ok = (
        expanded.min == Point3D(-10, -10, -10)
        and expanded.max == Point3D(110, 110, 110)
        and expanded.volume_mm3 == 120 * 120 * 120
    )
    overlap_box = bbox((50, 50, 50), (150, 150, 150))
    overlap = probe.intersection(overlap_box)
    intersection_ok = (
        overlap is not None
        and overlap.min == Point3D(50, 50, 50)
        and overlap.max == Point3D(100, 100, 100)
        and overlap.volume_mm3 == 50 * 50 * 50
    )
    disjoint = probe.intersection(bbox((1000, 1000, 1000), (1001, 1001, 1001)))
    disjoint_ok = disjoint is None
    checks.append(("Bounding box expansion is correct (uniform +margin on every face)", expansion_ok))
    checks.append(("Bounding box intersection is correct (overlap region + disjoint == None)", intersection_ok and disjoint_ok))

    # 3. Clash detection: overlap detected, severity assessed.
    clash_detected = len(scenario2_clashes) > 0
    severity_assessed = clash_detected and scenario2_clashes[0].severity in ("minor", "major", "critical")
    checks.append(("Clash detection finds the Scenario 2 crossing-pipe overlap", clash_detected))
    checks.append(("Clash severity is assessed to a known band (minor/major/critical)", severity_assessed))

    # 4. Angle constraints loaded and enforced — checked against the config's
    #    own bounds (whatever they are) rather than hardcoded mock values, so
    #    this holds for any jurisdiction config: the range must be non-empty,
    #    contain its own ideal, and reject values comfortably outside it.
    angle_rule = config.rules["angle_fire"]
    angle_ok = (
        angle_rule.angle_min_degrees < angle_rule.angle_max_degrees
        and angle_rule.angle_in_range(angle_rule.angle_ideal_degrees)
        and not angle_rule.angle_in_range(angle_rule.angle_min_degrees - 5)
        and not angle_rule.angle_in_range(angle_rule.angle_max_degrees + 5)
    )
    checks.append((
        f"Angle constraints loaded and enforced "
        f"({angle_rule.angle_min_degrees:.0f}-{angle_rule.angle_max_degrees:.0f} deg range from config)",
        angle_ok,
    ))

    # 5. Hospital flag never REDUCES clearance below standard — true by
    #    construction (effective_clearance_mm only ever adds a non-negative
    #    hospital_addition_mm), so this holds regardless of config. Equal
    #    values are a legitimate outcome when a config's source data doesn't
    #    differentiate hospital clearance (a data gap, not a bug) — flagged
    #    rather than silently reported as if it were a strict increase.
    hospital_clearance = angle_rule.effective_clearance_mm(building_type="hospital")
    standard_clearance = angle_rule.effective_clearance_mm(building_type="standard")
    hospital_never_less = hospital_clearance >= standard_clearance
    gap_note = (
        " — equal: hospital_addition_mm=0 in this config, a documented data gap, not a bug"
        if hospital_clearance == standard_clearance
        else ""
    )
    checks.append((
        f"Hospital flag never reduces clearance ({standard_clearance:.0f}mm -> {hospital_clearance:.0f}mm){gap_note}",
        hospital_never_less,
    ))

    # 6. Brace-type halo sizes track the config's own clearance values.
    #    When the config differentiates clearance per brace type (e.g. a
    #    mock config), halo volume must increase monotonically with it. When
    #    the config's source data does NOT differentiate (as in the real
    #    EN 1998-1 + DIN 4149 config — a documented data gap), every variant
    #    shares one clearance and volumes are expected to be identical, not
    #    "wrong" — this check accepts either case, but not a mismatch
    #    between what the config says and what the algorithm produced.
    clearance_by_variant = {v: rule.base_clearance_mm for v, rule in config.rules.items()}
    ordered = sorted(scenario1_results.items(), key=lambda kv: clearance_by_variant[kv[0]])
    volumes = [halo.halo_bbox_mm.volume_mm3 for _v, (halo, _clashes) in ordered]
    distinct_clearances = sorted(set(clearance_by_variant.values()))
    if len(distinct_clearances) > 1:
        ordering_ok = all(volumes[i] <= volumes[i + 1] for i in range(len(volumes) - 1))
        summary = ", ".join(f"{v}={clearance_by_variant[v]:.0f}mm" for v, _ in ordered)
        label = f"Brace types' halo volumes track their sourced clearances in order ({summary})"
    else:
        ordering_ok = len(set(volumes)) == 1
        label = (
            f"All {len(scenario1_results)} brace-type variants share one sourced clearance "
            f"({distinct_clearances[0]:.0f}mm — a documented data gap, see config.data_gaps) "
            "and therefore produce identical halo volumes, as expected"
        )
    checks.append((label, ordering_ok))

    # 7. BCF ZIP structure valid: bcf.version + project.bcfp, and one
    #    {guid}/{markup.bcf, viewpoint.bcfv, snapshot.png} folder per clash.
    top_level_ok = "bcf.version" in bcf_zip_names and "project.bcfp" in bcf_zip_names
    folders: dict[str, set] = {}
    for name in bcf_zip_names:
        if "/" in name:
            folder, filename = name.split("/", 1)
            folders.setdefault(folder, set()).add(filename)
    folder_count_ok = len(folders) == expected_clash_count
    files_ok = all(
        files == {"markup.bcf", "viewpoint.bcfv", "snapshot.png"} for files in folders.values()
    )
    bcf_structure_ok = top_level_ok and folder_count_ok and files_ok
    checks.append((
        f"BCF ZIP structure valid (bcf.version + project.bcfp + {len(folders)} topic folder(s) "
        f"of markup.bcf/viewpoint.bcfv/snapshot.png, matching {expected_clash_count} clash(es))",
        bcf_structure_ok,
    ))

    # 8. Pset is a valid IFC property set dict: JSON-serializable, single
    #    top-level Pset_-prefixed key, dict payload.
    try:
        json.dumps(pset)
        json_ok = True
    except TypeError:
        json_ok = False
    pset_ok = (
        json_ok
        and list(pset.keys()) == [PSET_HALO_RESERVATION]
        and PSET_HALO_RESERVATION.startswith("Pset_")
        and isinstance(pset[PSET_HALO_RESERVATION], dict)
    )
    checks.append((f"{PSET_HALO_RESERVATION} is a valid, JSON-serializable IFC property set dict", pset_ok))

    # 9. reporter imports cleanly — implicit: this script imports
    #    blue_halo_bcf_exporter (which imports bcf_generator) at module
    #    load time, so reaching this line already proves it.
    checks.append(("reporter imports without error (blue_halo_bcf_exporter, bcf_generator)", True))

    all_passed = True
    for label, passed in checks:
        status = "PASS" if passed else "FAIL"
        _out(f"  [{status}] {label}")
        all_passed = all_passed and passed

    _out(f"\n  {sum(p for _l, p in checks)}/{len(checks)} checks passed")
    return all_passed


