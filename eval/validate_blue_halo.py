def _print_element(el: MockElement) -> None:
    sx, sy, sz = el.bbox_mm.size
    _out(f"  Element:     {el.id}  ({el.ifc_class})")
    _out(f"  Material:    {el.material}")
    _out(f"  Description: {el.description}")
    _out(f"  Geometry:    {sx:.0f} x {sy:.0f} x {sz:.0f} mm  (bbox {el.bbox_mm.min} -> {el.bbox_mm.max})")


def _print_halo(label: str, halo, rule: ClearanceRule) -> None:
    sx, sy, sz = halo.halo_bbox_mm.size
    _out(f"    [{label}] variant={rule.variant:12s} clearance={halo.clearance_mm:6.1f}mm  "
         f"halo size={sx:.0f} x {sy:.0f} x {sz:.0f} mm  "
         f"(volume={halo.halo_bbox_mm.volume_mm3:,.0f} mm^3)")
    _out(f"             spacing: transverse={rule.spacing_transverse_m:.0f}m  "
         f"longitudinal={rule.spacing_longitudinal_m:.0f}m  "
         f"angle=[{rule.angle_min_degrees:.0f}-{rule.angle_max_degrees:.0f}] deg "
         f"(ideal {rule.angle_ideal_degrees:.0f} deg)")


def _print_clashes(clashes: list) -> None:
    if not clashes:
        _out("    Clashes: none")
        return
    for c in clashes:
        _out(f"    Clash: {c.clashing_element_class} ({c.clashing_element_id}) — "
             f"severity={c.severity.upper():8s} overlap={c.overlap_volume_mm3:,.0f} mm^3")


def _recommend_brace_type(results: dict) -> tuple:
    """Pick the brace type with the fewest clashes, tie-broken by smallest
    halo volume — a purely deterministic comparison over already-computed
    HaloVolume/ClashReport data, no new geometry work."""
    def _key(item):
        _variant, (halo, clashes) = item
        return (len(clashes), halo.halo_bbox_mm.volume_mm3)

    variant, (halo, clashes) = min(results.items(), key=_key)
    return variant, halo, clashes


