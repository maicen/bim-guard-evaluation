"""
validate_blue_halo.py
------------------------------------------------
Phase-3/4 validation harness for the Blue Halo seismic bracing clearance
algorithm (app/modules/blue_halo/halo_volume_generator.py) and its
Module 5 BCF/Pset export (app/modules/reporter/blue_halo_bcf_exporter.py).

Mirrors score_rule_extraction.py's style (plain script, print()-based,
no pytest). Runs the REAL Phase 1 core functions end-to-end — not a
hand-typed stand-in — against the REAL EN 1998-1 + DIN 4149 config
(hermes_case_study_and_config.json, generated by
app/modules/blue_halo/hermes_config_expanded.py) and synthetic mock
MEP elements, so results reflect what the algorithm actually does today
against real, if incomplete, standards data.

Scope (Phase 3 constraints):
  - No IFC file, no ifcopenshell entities. Elements are plain dataclasses
    carrying an already-known BoundingBox — this exercises
    generate_halo_volume_from_geometry / detect_halo_clash_against_geometry,
    the same core algorithm the ifcopenshell-based generate_halo_volume /
    detect_halo_clash wrap, minus IFC geometry extraction (which Phase 1's
    smoke test already covers separately).
  - Deterministic: no randomness, no wall-clock-dependent values feed any
    decision. Timestamps appear in dataclass fields but are never compared
    or asserted on.

Real-config caveat: hermes_case_study_and_config.json is real standards
data, but incomplete in ways its own metadata.data_gaps documents — e.g.
EN 1998-1 and DIN 4149 don't differentiate clearance per brace-hardware
variant, and neither breaks out a distinct hospital clearance addition.
The validation checks below are written to hold for ANY loaded config
(this real one, or a future mock/other-jurisdiction one) rather than
asserting the specific numbers only the old synthetic mock config had —
see each check's comment for how it adapts to what the config actually
contains, including the documented degenerate cases above.

Phase 4 addendum:
  Section "PHASE 4 — BCF / Pset export integration" below feeds the real
  HaloVolume / ClashReport objects produced by the five scenarios above
  into reporter.blue_halo_bcf_exporter, end to end: Phase 2 config
  loading -> Phase 1 generation/detection -> Phase 4 BCF-ZIP + Pset export.
  This is the only place this script imports reporter.

Usage:
    uv run python validate_blue_halo.py
"""

