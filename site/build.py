def git_commit() -> str:
    import subprocess

    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True
        ).strip()
    except Exception:
        return "unknown"


def main() -> None:
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)
    shutil.copy(SITE / "assets/style.css", DIST / "style.css")
    shutil.copytree(ROOT / "docs/publication/figures", DIST / "figures")
    (DIST / ".nojekyll").touch()

    commit = git_commit()
    for slug, title, src, repo_src in PAGES:
        md = expand_placeholders(src.read_text())
        # GitHub renders a list directly after a paragraph; python-markdown needs a blank line.
        md = re.sub(r"^((?![-*] )[^\n\d>|#\s][^\n]*)\n(?=[-*] )", r"\1\n\n", md, flags=re.M)
        body = markdown.markdown(md, extensions=["tables", "fenced_code", "toc", "sane_lists", "md_in_html"])
        body = badge_statuses(rewrite_links(body, repo_src))
        if repo_src:
            body = (
                f'<p class="src-note">Rendered from <a href="{REPO_URL}/blob/main/{repo_src}">'
                f"<code>{repo_src}</code></a>.</p>\n" + body
            )
        nav = "".join(
            f'<a href="{s}.html"{" aria-current=page" if s == slug else ""}>{t}</a>'
            for s, t, _, _ in PAGES
        )
        (DIST / f"{slug}.html").write_text(
            TEMPLATE.format(
                title=html.escape(title), nav=nav, body=body, repo=REPO_URL,
                repo_name="maicen/bim-guard-evaluation", commit=commit,
                description=html.escape(PAGE_DESCRIPTIONS[slug], quote=True),
                canonical=f"{BASE_URL}/" if slug == "index" else f"{BASE_URL}/{slug}.html",
                platform=PLATFORM_URL,
            )
        )
    urls = "".join(
        f"  <url><loc>{BASE_URL}/{'' if slug == 'index' else slug + '.html'}</loc></url>\n"
        for slug, _, _, _ in PAGES
    )
    (DIST / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{urls}</urlset>\n'
    )
    (DIST / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {BASE_URL}/sitemap.xml\n")
    print(f"built {len(PAGES)} pages -> {DIST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
