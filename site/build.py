"""Build the static evaluation site into site/dist/.

    uv run site/build.py

Everything is generated from files already in the repo (docs/publication/*,
research/CLAIMS.md, LIMITATIONS.md, ...) plus the hand-written pages in
site/content/. Nothing here re-runs an evaluation: the site only *presents*
committed artifacts, so a number can never appear on the site that is not
traceable to a file in the repository.

Content pages may use two placeholders:
    {{table:N}}              -> docs/publication/tables/table_N_*.tex as HTML
    {{figure:file.png|alt}}  -> <figure> using docs/publication/figures/file.png
"""
from __future__ import annotations

import html
import posixpath
import re
import shutil
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
DIST = SITE / "dist"
REPO_URL = "https://github.com/maicen/bim-guard-evaluation"
# Where the site is served (GitHub Pages project site); used for canonical URLs and the sitemap.
BASE_URL = "https://maicen.github.io/bim-guard-evaluation"
PLATFORM_URL = "https://bim-guard.xyz"

PAGE_DESCRIPTIONS = {
    "index": "Evaluation harnesses and empirical validation for BIM-Guard, an OpenBIM code-compliance platform: what the evidence supports and what it does not.",
    "results": "Real architecture-engine confusion matrix for BIM-Guard with Wilson confidence intervals, separated from simulated harnesses.",
    "claims": "Claims-to-evidence ledger: every headline BIM-Guard evaluation number, its producing script, artifact and verification status.",
    "limitations": "Methodological limitations of the BIM-Guard evaluation, stated plainly.",
    "determinism": "A run-to-run non-determinism bug in BIM-Guard's validation pipeline: found, root-caused, fixed and verified.",
    "reproduce": "Commands to re-run each BIM-Guard evaluation harness and reproduce its results.",
}

# (output slug, title, source markdown, repo-relative source path or None)
PAGES = [
    ("index", "Overview", SITE / "content/index.md", None),
    ("results", "Results", SITE / "content/results.md", None),
    ("claims", "Claims ledger", ROOT / "research/CLAIMS.md", "research/CLAIMS.md"),
    ("limitations", "Limitations", ROOT / "LIMITATIONS.md", "LIMITATIONS.md"),
    (
        "determinism",
        "Determinism audit",
        ROOT / "research/appendix_c_determinism_investigation.md",
        "research/appendix_c_determinism_investigation.md",
    ),
    ("reproduce", "Reproduce", SITE / "content/reproduce.md", None),
]
# Repo files that have a page on the site; links to them stay on-site.
LOCAL_TARGETS = {src: slug for slug, _, _, src in PAGES if src}

# --------------------------------------------------------------------------- LaTeX tables

_TEX_SYMBOLS = {
    r"\kappa": "κ", r"\tau": "τ", r"\ge": "≥", r"\le": "≤", r"\in": "∈",
    r"\rho": "ρ", r"\Delta": "Δ", r"\{": "{", r"\}": "}", r"\&": "&", r"\%": "%",
    r"\_": "_", "---": "—", "--": "–",
}


def _tex_inline(s: str) -> str:
    s = s.strip()
    for _ in range(3):  # \textbf{...} may nest once or twice
        s = re.sub(r"\\text(?:bf|it)\{([^{}]*)\}", r"\1", s)
    for k, v in _TEX_SYMBOLS.items():
        s = s.replace(k, v)
    return html.escape(s.replace("$", ""), quote=False)


def tex_table_to_html(path: Path) -> str:
    tex = path.read_text()
    caption = re.search(r"\\caption\{(.*)\}\s*$", tex, re.M)
    body = re.search(r"\\toprule(.*)\\bottomrule", tex, re.S)
    if not body:
        raise ValueError(f"no tabular body in {path}")
    rows_html, first = [], True
    for raw in re.split(r"\\midrule", body.group(1)):
        for line in raw.strip().split(r"\\"):
            line = line.strip()
            if not line:
                continue
            cells = [c for c in re.split(r"(?<!\\)&", line)]
            is_head = first or all(c.strip().startswith(r"\textbf") for c in cells)
            tag = "th" if is_head else "td"
            first = False
            rows_html.append(
                "<tr>" + "".join(f"<{tag}>{_tex_inline(c)}</{tag}>" for c in cells) + "</tr>"
            )
    cap = f"<caption>{_tex_inline(caption.group(1))}</caption>" if caption else ""
    src = f"{REPO_URL}/blob/main/{path.relative_to(ROOT).as_posix()}"
    return (
        f'<div class="table-wrap"><table>{cap}{"".join(rows_html)}</table></div>'
        f'<p class="src">Source: <a href="{src}">{path.name}</a> '
        "(generated by <code>eval/generate_publication_artifacts.py</code>)</p>"
    )


def expand_placeholders(md: str) -> str:
    def table(m: re.Match) -> str:
        n = m.group(1)
        (path,) = (ROOT / "docs/publication/tables").glob(f"table_{n}_*.tex")
        return tex_table_to_html(path)

    def figure(m: re.Match) -> str:
        name, alt = m.group(1), html.escape(m.group(2).strip())
        if not (ROOT / "docs/publication/figures" / name).exists():
            raise FileNotFoundError(name)
        return f'<figure><img src="figures/{name}" alt="{alt}"><figcaption>{alt}</figcaption></figure>'

    md = re.sub(r"\{\{table:(\d+)\}\}", table, md)
    return re.sub(r"\{\{figure:([^|}]+)\|([^}]*)\}\}", figure, md)


# --------------------------------------------------------------------------- link rewriting


def rewrite_links(body: str, repo_src: str | None) -> str:
    """Repo-relative links -> on-site page if one exists, else the file on GitHub."""
    if repo_src is None:
        return body
    base = posixpath.dirname(repo_src)

    def sub(m: re.Match) -> str:
        href = m.group(1)
        if re.match(r"^(?:[a-z][a-z0-9+.-]*:|#|/)", href, re.I):
            return m.group(0)
        target, _, frag = href.partition("#")
        resolved = posixpath.normpath(posixpath.join(base, target))
        if resolved in LOCAL_TARGETS:
            new = f"{LOCAL_TARGETS[resolved]}.html" + (f"#{frag}" if frag else "")
        else:
            kind = "tree" if (ROOT / resolved).is_dir() else "blob"
            new = f"{REPO_URL}/{kind}/main/{resolved}" + (f"#{frag}" if frag else "")
        return f'href="{new}"'

    return re.sub(r'href="([^"]*)"', sub, body)


# --------------------------------------------------------------------------- templating

STATUS_CLASSES = ["reproduced", "archived-artifact", "single-run", "not-verified", "simulated", "retired-domain"]


def badge_statuses(body: str) -> str:
    """Colour the backticked status words (`simulated`, `reproduced`, ...) as badges."""
    for s in STATUS_CLASSES:
        body = body.replace(f"<code>{s}</code>", f'<code class="badge {s}">{s}</code>')
    return body


